
import re
from collections import Counter


def diagnose_action_format(raw_output: str) -> str | None:
    """
    Classify formatting problems in a recorded model response.

    This diagnostic function is independent of the main action
    parser. It only inspects the original model output.

    It does not repair commands, execute tools, or change the
    evaluation result.

    Parameters:
        raw_output: The original text generated by the model.

    Returns:
        A diagnostic category describing the formatting issue,
        or None if no supported formatting issue is detected.
    """

    # Find lines that appear to contain an action command.
    action_lines = [
        line.strip()
        for line in raw_output.splitlines()
        if re.match(r"^action\b", line.strip(), flags=re.IGNORECASE)
    ]

    # Identify missing or repeated action commands.
    if not action_lines:
        return "missing_action"

    if len(action_lines) > 1:
        return "multiple_actions"

    action_line = action_lines[0]

    # Check whether the action uses the required prefix.
    if not action_line.startswith("Action:"):
        return "nonstandard_prefix"

    # Extract the action name and argument without executing them.
    pattern = r"Action:\s*([A-Za-z]+)\[([^\[\]\n]*)\]"
    match = re.fullmatch(pattern, action_line)

    if match is None:
        return "malformed_command"

    action_name = match.group(1)
    argument = match.group(2)

    # Check whether the action name belongs to the supported set.
    if action_name not in {"Search", "Calculate", "Finish"}:
        return "unsupported_action"

    # Detect commands without a meaningful argument.
    if not argument.strip():
        return "empty_argument"

    return None


def summarize_diagnostic_failures(
    raw_outputs: list[str],
) -> dict[str, int]:
    """
    Count command-format problems in recorded model outputs.

    Each input string represents one recorded model call.
    The function uses the independent diagnostic parser
    to classify formatting issues and count their frequency.

    Valid command formats are not counted as formatting errors.

    This function does not modify outputs, execute tools,
    or change any evaluation result.

    Parameters:
        raw_outputs: Original model responses collected during
                     evaluation or diagnostic analysis.

    Returns:
        A dictionary containing the number of calls for each
        detected error category and the total number of calls
        affected by command-format problems.
    """

    # Count how often each formatting problem occurs.
    error_counts: Counter[str] = Counter()

    for raw_output in raw_outputs:

        # Analyze the original response without modifying it.
        reason = diagnose_action_format(raw_output)

        # Count only detected command-format problems.
        if reason is not None:
            error_counts[reason] += 1

    # Convert the counts into a standard Python dictionary.
    summary = dict(error_counts)

    # Count calls affected by a detected formatting problem.
    summary["total_affected_calls"] = sum(error_counts.values())

    return summary