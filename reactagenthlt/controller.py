import re
from reactagenthlt.tools import Calculator, SearchEngine, RetrievalTokenizer
from collections.abc import Callable


def parse_action(model_output: str) -> tuple[str, str]:
    """
    Extract an action and its argument from the language model's output.

    The ReAct agent expects the model to produce one of these actions:
        Action: Search[query]
        Action: Calculate[expression]
        Action: Finish[answer]

    The model may also include a Thought line before the action.

    Parameters:
        model_output: The text generated by the language model.

    Returns:
        A tuple containing the action name and its argument.

    Raises:
        ValueError: If the output does not contain exactly one
                    valid action.
    """

    # Split the model's output into separate lines.
    lines = model_output.splitlines()

    # Find all lines that start with the expected action prefix.
    action_lines = [
        line.strip()
        for line in lines
        if line.strip().startswith("Action:")
    ]

    # The controller expects exactly one action per model response.
    if len(action_lines) != 1:
        raise ValueError("Expected exactly one Action line.")

    # Check the action format and extract its name and argument.
    pattern = r"Action:\s*(Search|Calculate|Finish)\[([^\[\]\n]+)\]"
    match = re.fullmatch(pattern, action_lines[0])

    if match is None:
        raise ValueError("Invalid action format.")

    # Separate the action name from the provided argument.
    action_name = match.group(1)
    argument = match.group(2).strip()

    return action_name, argument


class InvalidToolInput(ValueError):
    """
    Represent an invalid input supplied to a ReAct tool.

    This exception distinguishes invalid model-generated
    tool arguments from failures inside the tool itself.
    """


def execute_calculation(expression: str) -> str:
    """
    Execute a mathematical expression using Federico's Calculator tool.

    Before calling the calculator, this function checks that the
    expression contains only basic arithmetic characters.

    This validation is important because the expression is generated
    by a language model and should not be trusted automatically.

    Parameters:
        expression: The mathematical expression requested by the model.

    Returns:
        The calculation result converted to a string.

    Raises:
        ValueError: If the expression is unsafe or cannot be calculated.
    """

    # Allow only numbers and basic arithmetic symbols.
    allowed_pattern = r"[0-9+\-*/(). %]+"

    # Reject long expressions, unsupported characters, and exponentiation.
    if (
        len(expression) > 100
        or re.fullmatch(allowed_pattern, expression) is None
        or "**" in expression
        or "//" in expression
    ):
        raise InvalidToolInput("Invalid or unsupported calculation.")

    # Use the Calculator already implemented by Federico.
    calculator = Calculator()

    try:
        result = calculator.calculate(expression)

    except (ArithmeticError, SyntaxError) as error:
        # Mathematical errors are treated as invalid tool inputs.
        raise InvalidToolInput("Calculation failed.") from error


    # Return text because ReAct observations are passed back to the model.
    return str(result)


def normalize_search_query(query: str) -> str:
    """
    Normalize a search query using the existing retrieval tokenizer.

    The tokenizer converts text to lowercase and extracts Unicode
    word tokens, removing punctuation consistently with SearchEngine.

    Parameters:
        query: The original search query generated by the model.

    Returns:
        A normalized search query with tokens separated by spaces.
    """

    # Reuse Federico's tokenizer to ensure consistent processing.
    tokenizer = RetrievalTokenizer()

    # Convert the query into lowercase word tokens.
    tokens = tokenizer.tokenize(query)

    # Reconstruct a normalized query for the search engine.
    return " ".join(tokens)


def execute_search(query: str, search_engine: SearchEngine) -> str:
    """
    Search for information using Federico's SearchEngine tool.

    The ReAct controller receives a search query generated by the
    language model and passes it to the existing search engine.

    The search engine returns a pandas DataFrame containing the
    retrieved documents. This function converts those documents
    into a single text observation for the language model.

    Parameters:
        query: The search query generated by the language model.
        search_engine: An existing SearchEngine instance.

    Returns:
        A text containing the retrieved documents.

    Raises:
        ValueError: If the search query is empty.
    """


    # Normalize the query using the same rules as SearchEngine.
    normalized_query = normalize_search_query(query)

    # Reject queries without searchable words.
    if not normalized_query:
        raise InvalidToolInput("Search query cannot be empty.")

    # Execute the search using the normalized query.
    results = search_engine.search(normalized_query)


    # Handle the case where no documents are returned.
    if results.empty:
        return "No documents found."

    # Combine the retrieved documents into one text observation.
    # Each document is separated by a blank line for readability.
    documents = results["document"].tolist()

    return "\n\n".join(documents)


class InvalidReActRun(ValueError):
    """
    Represent an invalid ReAct run during strict evaluation.

    The exception stores the failure reason and the original
    model output for later analysis and error reporting.
    """

    def __init__(self, reason: str, raw_output: str) -> None:
        super().__init__(reason)
        self.reason = reason
        self.raw_output = raw_output



class ReActBudgetExceeded(RuntimeError):
    """
    Represent a ReAct run that exhausted its decision-step budget.

    Store the dataset, number of steps used, and last model
    output so the evaluation pipeline can record the failure.
    """

    def __init__(
        self,
        dataset: str,
        steps_used: int,
        last_output: str,
    ) -> None:
        super().__init__(
            f"Agent did not finish within {steps_used} steps."
        )

        self.reason = "budget_exhausted"
        self.dataset = dataset
        self.steps_used = steps_used
        self.last_output = last_output



class ReActToolFailure(RuntimeError):
    """
    Represent a failure during external tool execution.

    Tool execution failures are kept separate from invalid
    model actions and invalid tool inputs.

    The original model output is preserved for evaluation.
    """

    def __init__(
        self,
        tool_name: str,
        raw_output: str,
    ) -> None:
        super().__init__(
            f"{tool_name} failed during execution."
        )

        self.reason = "tool_failure"
        self.tool_name = tool_name
        self.raw_output = raw_output


def run_react(
    question: str,
    generate: Callable[[str], str],
    search_engine: SearchEngine | None = None,
    max_steps: int | None = None,
    strict: bool = False,
    dataset: str = "hotpotqa",
    trace: list[dict[str, str | int]] | None = None,
) -> str:
    """
    Run the main ReAct reasoning and action loop.

    The controller sends the current context to a language model,
    reads the generated action, and executes the appropriate tool.

    When a tool is used, its result is added to the context as an
    observation. The updated context is then passed back to the model.

    The process continues until the model produces a Finish action
    or the maximum number of steps is reached.

    Parameters:
        question: The original question to be answered.
        generate: A function that receives context and returns
                  text generated by the language model.
        search_engine: An existing SearchEngine instance.
        strict: Whether invalid actions and tool inputs should
                immediately terminate the run.
        dataset: Evaluation dataset ("hotpotqa" or "gsm8k").
        max_steps: Optional step limit override. By default,
                   HotpotQA allows 7 steps and GSM8K allows 9.
                   Each model response, including Finish,
                   counts as one step.
        trace: Optional list used to collect model outputs,
               actions, observations, and step information.

    Returns:
        The final answer extracted from Finish[answer].

    Raises:
        ValueError: If the question is empty or an unavailable
                    tool is requested.
        RuntimeError: If the agent reaches the step limit
                      without producing a final answer.
    """

    # Reject empty questions before starting the agent.
    if not question.strip():
        raise ValueError("Question cannot be empty.")

    # The agent must have at least one step to produce an answer.

    # Maximum decision steps defined for each evaluation dataset.
    # A Finish action counts as one model decision step.
    step_limits = {
        "hotpotqa": 7,
        "gsm8k": 9,
    }

    # Validate the dataset before starting the agent.
    dataset_name = dataset.lower()

    if dataset_name not in step_limits:
        raise ValueError(f"Unsupported dataset: {dataset}")

    # Use the dataset-specific limit unless explicitly overridden.
    if max_steps is None:
        max_steps = step_limits[dataset_name]

    # Reject invalid step limits.
    if max_steps < 1:
        raise ValueError("Maximum steps must be at least 1.")


    # Start the conversation with the original question.
    # The model-specific instructions will be configured separately.
    context = f"Question: {question.strip()}\n"

    # Preserve the last model response for evaluation diagnostics.
    last_model_output = ""

    # Run the agent for a limited number of steps.
    # The limit prevents the agent from running indefinitely.
    for step in range(max_steps):

        # Ask the language model to generate its next action.
        model_output = generate(context)

        # Keep the original output without modifying its contents.
        last_model_output = model_output


        # Create a record for the current model decision step.
        # Preserve the original model output for later evaluation.
        step_record: dict[str, str | int] = {
            "step": step + 1,
            "raw_output": model_output,
        }

        # Store the record only when tracing is requested.
        if trace is not None:
            trace.append(step_record)


        # Extract the action name and its argument.
        # Parse the model response and preserve invalid outputs.
        try:
            action, argument = parse_action(model_output)

        except ValueError as error:
            if strict:
                # Record why strict evaluation rejected this action.
                step_record["status"] = "invalid"
                step_record["failure_reason"] = "invalid_action"

                raise InvalidReActRun(
                    reason="invalid_action",
                    raw_output=model_output,
                ) from error

            raise


        # Reject empty final answers during strict evaluation.
        if strict and action == "Finish" and not argument:
            step_record["status"] = "invalid"
            step_record["failure_reason"] = "invalid_final_answer"

            raise InvalidReActRun(
                reason="invalid_final_answer",
                raw_output=model_output,
            )


        # Record the parsed action without modifying model output.
        step_record["action"] = action
        step_record["argument"] = argument


        # Save the model's response in the conversation history.
        context += f"\n{model_output.strip()}\n"

        # Finish immediately when the model provides its final answer.

        # Record successful termination of the ReAct loop.
        if action == "Finish":
            step_record["status"] = "finished"
            return argument


        # Execute the appropriate tool based on the model's action.
        # A search action requires an initialized search engine.
        if action == "Search" and search_engine is None:
            raise ValueError("Search engine is not available.")

        # Execute the requested tool and handle expected tool errors.
        # A failed tool call becomes an observation instead of
        # terminating the entire ReAct loop.
        try:
            if action == "Search":
                observation = execute_search(argument, search_engine)

            elif action == "Calculate":
                observation = execute_calculation(argument)

        except InvalidToolInput as error:

            # Strict evaluation stops on invalid tool inputs.
            if strict:
                # Preserve the invalid tool-input failure in the trace.
                step_record["status"] = "invalid"
                step_record["failure_reason"] = "invalid_tool_input"

                raise InvalidReActRun(
                    reason="invalid_tool_input",
                    raw_output=model_output,
                ) from error

            # Non-strict mode allows the model to recover.
            observation = f"Tool error: {error}"


        except Exception as error:
            # Record unexpected tool execution failures separately.
            step_record["status"] = "tool_failure"
            step_record["failure_reason"] = "tool_failure"

            # Unexpected tool execution failures are not treated
            # as invalid model actions or invalid tool inputs.
            raise ReActToolFailure(
                tool_name=action,
                raw_output=model_output,
            ) from error



        # Add the tool result to the conversation history.
        # The model will receive this observation in the next step.
        context += f"Observation: {observation}\n"


        # Record the tool observation for diagnostic analysis.
        step_record["observation"] = observation
        step_record["status"] = "continued"


    # Mark the last recorded step as budget exhaustion.
    # The step record is already part of trace when tracing is enabled.
    step_record["status"] = "budget_exhausted"
    step_record["failure_reason"] = "budget_exhausted"


    # Report budget exhaustion with structured failure metadata.
    raise ReActBudgetExceeded(
        dataset=dataset_name,
        steps_used=max_steps,
        last_output=last_model_output,

    )



